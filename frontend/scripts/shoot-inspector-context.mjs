import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.addInitScript(() => localStorage.setItem('gantry:locale:v1', 'zh-CN'));
await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: /使用(此)?模板 桁架精工/ }).click();
await page.waitForSelector('.builder');
const scroller = page.locator('.inspector-scroll');
await scroller.evaluate((node) => node.scrollTo({ top: 420 }));
await page.getByRole('textbox', { name: '主标题 / TITLE' }).focus();
await page.waitForTimeout(300);
await page.screenshot({ path: 'E:/asd/gantry-studio/frontend/screenshots/builder-inspector-context.png' });
await browser.close();
console.log('inspector context screenshot done');
