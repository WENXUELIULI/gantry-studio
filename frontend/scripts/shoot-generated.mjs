import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
await page.addInitScript(() => localStorage.setItem('gantry:locale:v1', 'zh-CN'));
await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' });
await page.getByLabel('搜索').fill('工业编辑风');
await page.waitForTimeout(700);
await page.locator('#templates').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'E:/asd/gantry-studio/frontend/screenshots/gallery-generated.png' });
await browser.close();
console.log('gallery generated screenshot done');
